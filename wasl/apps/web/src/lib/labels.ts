export function label(group: keyof typeof LABELS | string, value: string | null | undefined, locale: Locale): string {
  if (!value) return "—";
  const g = LABELS[group];
  const entry = g?.[value];
  if (!entry) return value.replace(/_/g, " ");
  return locale === "ar" ? entry[0] : entry[1];
}
