"""Runs every scenario preset × policy × replication through the SimPy model and prints a
Markdown table (mean ± 95% CI). Used to produce docs/EXPERIMENTS.md. Fully reproducible:
    python3 scripts/run_experiments.py --seed 20261108 --reps 3 > docs/EXPERIMENTS.md
"""
import argparse, json, math, statistics, sys, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "services" / "intelligence"))
from wasl_intel.presets import preset  # noqa: E402
from wasl_intel.simulation import run, SIM_VERSION  # noqa: E402
from wasl_intel import ml  # noqa: E402

T95 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571}
PRESETS = ["NORMAL", "PEAK_ARRIVALS", "DOCK_FAILURE", "WORKFORCE_SHORTAGE", "DELAYED_TRUCKS", "QUALITY_SURGE", "MIXED_DISRUPTION"]
POLICIES = ["FCFS", "FIXED_APPOINTMENTS", "OR_ONLY", "FULL_WASL"]
METRICS = [("avg_wait_min", "On-site wait (min)"), ("p95_wait_min", "P95 wait (min)"), ("avg_total_delay_min", "Total delay (min)"), ("avg_queue_length", "Avg yard queue"), ("dock_utilization", "Dock util."), ("makespan_min", "Makespan (min)")]

def fmt(xs):
    m = statistics.mean(xs)
    if len(xs) < 2:
        return f"{m:.2f}"
    ci = T95.get(len(xs) - 1, 1.96) * statistics.stdev(xs) / math.sqrt(len(xs))
    return f"{m:.2f} ± {ci:.2f}"

ap = argparse.ArgumentParser(); ap.add_argument("--seed", type=int, default=20261108); ap.add_argument("--reps", type=int, default=3)
a = ap.parse_args()
models = [f"{m['model_name']}@{m['version']}" for m in ml.registry.list() if m["is_active"]]
print(f"# Simulation experiments\n\nGenerated by `scripts/run_experiments.py --seed {a.seed} --reps {a.reps}` · simulator `{SIM_VERSION}` · models {', '.join(models) or 'none'} · {time.strftime('%Y-%m-%d')}.\n")
print("All values are **computed simulation results on synthetic data** (mean ± 95% CI over replications; common random numbers per replication). They do not demonstrate performance in a real warehouse. Lower is better except dock utilisation.\n")
raw = {}
for p in PRESETS:
    print(f"\n## {p}\n\n| Policy | " + " | ".join(n for _, n in METRICS) + " |\n|---|" + "---|" * len(METRICS))
    for pol in POLICIES:
        res = [run(preset(p), pol, a.seed + r)["metrics"] for r in range(a.reps)]
        raw[f"{p}/{pol}"] = res
        print(f"| {pol} | " + " | ".join(fmt([x[k] for x in res]) for k, _ in METRICS) + " |")
    sys.stdout.flush()
Path(__file__).resolve().parent.parent.joinpath("docs", "experiments.raw.json").write_text(json.dumps(raw, indent=1))
